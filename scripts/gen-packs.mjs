// Regenerate presets/packs.mjs from presets/packs.json.
//
// The middleware imports packs.mjs, not the json: magpie runs middleware on
// moejs, which does not do `import … with { type: "json" }`. Keeping one source
// of truth (the json, which the README links to) plus a generated module is the
// only way to avoid the two drifting — tests/packs.test.mjs fails if they do.
//
//   node scripts/gen-packs.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const src = join(root, "presets", "packs.json")
const out = join(root, "presets", "packs.mjs")

const packs = JSON.parse(readFileSync(src, "utf8"))
const body = JSON.stringify(packs, null, 2)

writeFileSync(
  out,
  "// Generated by scripts/gen-packs.mjs from presets/packs.json — do not edit by hand.\n" +
    "// Inlined so the module loads without import attributes (magpie runs middleware on moejs).\n" +
    `export default ${body}\n`,
)
console.log(`wrote ${out} (${Object.keys(packs.presets || {}).length} presets, boost=${(packs.boost || "").length} chars, repair=${(packs.repair || "").length} chars)`)